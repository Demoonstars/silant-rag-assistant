def run_evaluation():
    """Прогоняет контрольный набор вопросов через RAG и сохраняет подробный отчет в test_results.md."""
    print("=== Запуск тестирования RAG-сервиса СИЛАНТ на эталонном наборе (10 кейсов) ===\n", flush=True)
    rag = SilantRAG(top_k=14)

    results = []
    passed_count = 0

    for idx, case in enumerate(TEST_SUITE, 1):
        print(f"[{idx}/{len(TEST_SUITE)}] Проверка {case['id']} ({case['category']})...", flush=True)
        res = rag.ask(
            question=case["question"],
            selected_model=case["model"],
            chat_history=[]
        )

        ans_low = res["answer"].lower()
        # Проверяем наличие ключевых маркеров эталона в ответе
        matched_markers = [
            m for m in case["expected_markers"]
            if m.lower() in ans_low
        ]
        # Кейс считается успешно пройденным, если найдена хотя бы половина ключевых маркеров и нет технической ошибки API
        is_ok = (len(matched_markers) >= max(1, len(case["expected_markers"]) // 2)) and ("⚠️ сервер" not in ans_low)
        if is_ok:
            passed_count += 1

        sources_short = [
            f"{s['doc_title']} | {s['section']} (стр. {s['page']})"
            for s in res["sources"]
        ]

        results.append({
            "id": case["id"],
            "category": case["category"],
            "model": case["model"],
            "question": case["question"],
            "reference_answer": case["reference_answer"],
            "actual_answer": res["answer"],
            "sources": sources_short,
            "elapsed_sec": res["elapsed_sec"],
            "status": "ПРОЙДЕН" if is_ok else "ТРЕБУЕТ ВНИМАНИЯ"
        })
        print(f"    -> Статус: {results[-1]['status']} | Время: {res['elapsed_sec']} сек.\n", flush=True)
        time.sleep(2)

    # Сохраняем JSON-версию результатов
    out_json = Path("data/test_results.json")
    out_json.parent.mkdir(parents=True, exist_ok=True)
    with open(out_json, "w", encoding="utf-8") as f:
        json.dump(results, f, ensure_ascii=False, indent=2)

    # Формируем чистовой отчет в формате Markdown для сдачи проекта
    avg_time = round(sum(r["elapsed_sec"] for r in results) / len(results), 1)
    md_lines = [
        "# Отчет о проверке RAG-ассистента «СИЛАНТ» на тестовом наборе вопросов\n",
        f"**Дата проведения проверки:** {datetime.now().strftime('%d.%m.%Y %H:%M')}  ",
        f"**Всего контрольных сценариев:** {len(results)}  ",
        f"**Успешно пройдено:** {passed_count} из {len(results)} ({int(passed_count / len(results) * 100)}%)  ",
        f"**Среднее время генерации ответа:** {avg_time} сек. (требование ТЗ: до 60 сек.)\n",
        "---\n",
        "## 1. Сводная таблица результатов тестирования\n",
        "| ID | Категория проверки | Выбранная модель | Время, сек | Статус |",
        "| :--- | :--- | :--- | :---: | :---: |"
    ]

    for r in results:
        md_lines.append(
            f"| **{r['id']}** | {r['category']} | `{r['model']}` | {r['elapsed_sec']} | **{r['status']}** |"
        )

    md_lines.append("\n---\n")
    md_lines.append("## 2. Детальное сличение с эталонными ответами\n")

    for r in results:
        md_lines.append(f"### {r['id']}. {r['category']}")
        md_lines.append(f"- **Выбранная модель в интерфейсе:** `{r['model']}`")
        md_lines.append(f"- **Вопрос пользователя:** «{r['question']}»")
        md_lines.append(f"- **Время ответа:** {r['elapsed_sec']} сек. | **Оценка:** `{r['status']}`\n")
        md_lines.append(f"**Эталонный ответ (по документации ООО «ЧЗСА»):**\n> {r['reference_answer']}\n")
        md_lines.append("**Фактический ответ RAG-ассистента:**\n")
        md_lines.append(r["actual_answer"] + "\n")
        if r["sources"]:
            md_lines.append("**Найденные системой страницы первоисточника:**")
            for s_line in r["sources"]:
                md_lines.append(f"- `{s_line}`")
        else:
            md_lines.append("*Источники скрыты (режим предварительного уточнения модели).*")
        md_lines.append("\n---\n")

    report_path = Path("test_results.md")
    with open(report_path, "w", encoding="utf-8") as f:
        f.write("\n".join(md_lines))

    print(f"=== ГОТОВО! Отчет сохранен в файл: {report_path.resolve()} ===", flush=True)


if __name__ == "__main__":
    run_evaluation()